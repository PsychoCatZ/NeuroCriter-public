def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    client = anthropic.Anthropic()
    out = ["# Результаты пробы голоса (Haiku 5.5)\n"]
    total_in = total_out = 0
    for title, state, menu, event in SCENARIOS:
        user = f"{state}\n{menu}\n{event}"
        resp = client.messages.create(
            model=MODEL,
            max_tokens=400,
            system=SYSTEM,
            output_config={"effort": "low"},
            messages=[{"role": "user", "content": user}],
        )
        text = "".join(b.text for b in resp.content if b.type == "text")
        total_in += resp.usage.input_tokens
        total_out += resp.usage.output_tokens
        block = f"## {title}\n\n```\n{user}\n```\n\n{text}\n"
        print(block)
        out.append(block)
    cost = total_in / 1e6 * PRICE_IN + total_out / 1e6 * PRICE_OUT
    footer = (f"\nТокены: вход {total_in}, выход {total_out}. "
              f"Оценка стоимости прогона: ${cost:.5f}\n")
    print(footer)
    out.append(footer)
    Path(__file__).with_name("voice_test_results.md").write_text(
        "\n".join(out), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
