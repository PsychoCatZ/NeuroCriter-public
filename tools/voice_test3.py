def build_user(rng, sc, last_replies):
    menu = sc["menu"][:]
    rng.shuffle(menu)
    if len(menu) > 4 and rng.random() < 0.5:
        menu.pop()
    impulse = rng.choice(IMPULSES)
    parts = [sc["state"], "Допустимые действия: " + ", ".join(menu) + ".",
             "ИМПУЛЬС МОМЕНТА: " + impulse + "."]
    memory_used = None
    if sc["memories"] and rng.random() < MEMORY_CHANCE:
        memory_used = rng.choice(sc["memories"])
        parts.append("ВОСПОМИНАНИЕ СЕЙЧАС: " + memory_used)
    if last_replies:
        parts.append("ТВОИ ПОСЛЕДНИЕ РЕПЛИКИ (не повторяй их зачин):\n"
                     + "\n".join("- " + r for r in last_replies[-3:]))
    parts.append(sc["event"])
    return "\n".join(parts), impulse, memory_used


def parse(text):
    action = say = ""
    for line in text.splitlines():
        if line.startswith("ДЕЙСТВИЕ:"):
            action = line.split(":", 1)[1].strip()
        elif line.startswith("РЕПЛИКА:"):
            say = line.split(":", 1)[1].strip()
    return action, say


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    client = anthropic.Anthropic()
    rng = random.Random(SEED)
    out = [f"# Проба голоса №3 ({MODEL})\n"]
    total_in = total_out = 0
    for sc in SCENARIOS:
        head = f"## {sc['title']}\n"
        print(head)
        out.append(head)
        last, actions, openers = [], [], []
        for i in range(1, sc["runs"] + 1):
            user, impulse, mem = build_user(rng, sc, last)
            resp = client.messages.create(
                model=MODEL,
                max_tokens=400,
                system=SYSTEM,
                output_config={"effort": "low"},
                messages=[{"role": "user", "content": user}],
            )
            text = "".join(b.text for b in resp.content if b.type == "text")
            total_in += resp.usage.input_tokens
            total_out += resp.usage.output_tokens
            action, say = parse(text)
            last.append(say)
            actions.append(action)
            openers.append(say.split()[0].lower() if say.split() else "")
            block = (f"**Прогон {i}**  (импульс: {impulse}; "
                     f"память: {'да' if mem else 'нет'})\n\n{text}\n")
            print(block)
            out.append(block)
        summary = (f"_Разных действий: {len(set(actions))} из {len(actions)}; "
                   f"разных первых слов: {len(set(openers))} из {len(openers)}._\n")
        print(summary)
        out.append(summary)
    cost = total_in / 1e6 * PRICE_IN + total_out / 1e6 * PRICE_OUT
    footer = (f"\nТокены: вход {total_in}, выход {total_out}. "
              f"Оценка стоимости: ${cost:.5f}\n")
    print(footer)
    out.append(footer)
    Path(__file__).with_name(f"voice_test3_results{SUFFIX}.md").write_text(
        "\n".join(out), encoding="utf-8")
    return 0


