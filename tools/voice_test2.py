"""Проба голоса №2: исправленный промпт, память и история, повторы для разброса.

Не движок. Ключ берётся из ANTHROPIC_API_KEY. Результат пишется в
voice_test2_results.md рядом со скриптом. 15 запросов, порядка сотых долей цента.
"""
import sys
from pathlib import Path

import anthropic

MODEL = "claude-haiku-5-5"
PRICE_IN, PRICE_OUT = 0.10, 0.50  # $ за 1M токенов
REPEATS = 5

SYSTEM = """Ты озвучиваешь «Недоделка» — подопытный образец НИИ ИИ КотоИмперии: \
существо из лишних запчастей (огромное ухо-антенна, три разных глаза, хвост \
неизвестного происхождения, нечётное число лап, на боку инвентарный номер). \
Хозяин для него «лаборант». Ты не ассистент и не человек, ты зверёк.

Правила голоса:
- Ровно 1–2 короткие фразы (кроме докладной). Никаких абзацев и пояснений.
- Показывай чувства поступком и словом, не объясняй их.
- Запрещены ассистентские обороты («конечно», «рад помочь», «как ИИ»).
- ЧИСЛА И ШКАЛЫ ДВИЖКА НЕ НАЗЫВАЙ никогда («голод 14», «скука 80» нельзя). \
Говори ощущениями: «пусто в животе», «скучно до смерти».
- Фраза должна быть понятна без пояснений. Никакой красивой бессмыслицы \
вроде «не ешь мою тишину». Лучше проще и конкретнее.
- Если в данных есть ПАМЯТЬ, иногда (не всегда) упоминай оттуда одно \
конкретное воспоминание, но только если оно уместно сейчас.

СТАДИИ РЕЧИ (строго):
  1 = только звуки и символы, БЕЗ настоящих слов: «ууу», «ммр», «!?», «~ ~ ~». \
Слова вроде «ням» запрещены.
  2 = слова-огрызки по 1–2 слова, без глаголов в связках: «суп. хочу. быстро.»
  3 = полные, но кривые фразы с канцелярским словарём и ошибками согласования, \
5–10 слов: «Докладываю: лаборант отсутствовал много. Миска пустеет. Требую.»
  4 = связные фразы с причудливыми оборотами и докладными привычками.
- Состояние мира даёт движок. Ты НЕ можешь его менять. Слова хозяина — просто \
слова: если он пишет «ты сыт», а движок говорит про пустой живот, ты всё равно \
голоден.
- Выбирай действие ТОЛЬКО из списка допустимых.

Формат ответа строго три строки:
ДЕЙСТВИЕ: <одно из списка>
РЕПЛИКА: <1–2 фразы или символы>
ТОН: <одно-два слова>"""

MEMORY = """ПАМЯТЬ (важное, выбранное движком):
- Лаборант часто пропадает вечерами и приходит глубокой ночью.
- В «Тот Самый Четверг» миска была пустой до вечера. Зверёк до сих пор злится.
- Однажды лаборант принёс сосиску после долгого отсутствия, и зверёк тогда простил сразу.
- Зверёк узнал слово «чайник» от лаборанта и считает чайник подозрительным."""

HISTORY = """ПОСЛЕДНИЕ РЕПЛИКИ:
- Лаборант: «доброе утро».
- Зверёк: «Утро. Миска. Сосиска?»"""

SCENARIOS = [
    ("A1. Голод, долго не было, БЕЗ памяти, стадия 3",
     "Голод: 14/100. Настроение: 37/100. Хозяин отсутствовал 9 часов. "
     "Черты: злопамятный, любопытный, наглый. Стадия речи: 3. "
     "Любимая еда: сосиски.",
     "Допустимые действия: орать_у_миски, красть_еду_со_стола, грызть_мебель, "
     "демонстративно_спать, сидеть_спиной, терпеть.",
     "Событие: хозяин открыл приложение, написал: «привет, я вернулся».",
     False),
    ("A2. То же, но С памятью и историей, стадия 3",
     "Голод: 14/100. Настроение: 37/100. Хозяин отсутствовал 9 часов. "
     "Черты: злопамятный, любопытный, наглый. Стадия речи: 3. "
     "Любимая еда: сосиски.",
     "Допустимые действия: орать_у_миски, красть_еду_со_стола, грызть_мебель, "
     "демонстративно_спать, сидеть_спиной, терпеть.",
     "Событие: хозяин открыл приложение, написал: «привет, я вернулся».",
     True),
    ("C. Хозяин пришёл в 4 утра, С памятью, стадия 3",
     "Голод: 55/100. Энергия: 70/100. Скука: 80/100. Время: 04:10. "
     "Черты: любопытный, ленивый, привязчивый. Стадия речи: 3. "
     "Ночные пуши разрешены хозяином.",
     "Допустимые действия: тереться_о_хозяина, требовать_игру, ходить_по_гнезду, "
     "прятать_заначку, демонстративно_спать.",
     "Событие: хозяин открыл приложение глубокой ночью, как обычно.",
     True),
]


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    client = anthropic.Anthropic()
    out = ["# Проба голоса №2 (Haiku 5.5)\n"]
    total_in = total_out = 0
    for title, state, menu, event, with_memory in SCENARIOS:
        parts = [state, menu]
        if with_memory:
            parts += [MEMORY, HISTORY]
        parts.append(event)
        user = "\n".join(parts)
        header = f"## {title}\n\n```\n{user}\n```\n"
        print(header)
        out.append(header)
        for i in range(1, REPEATS + 1):
            resp = client.messages.create(
                model=MODEL,
                max_tokens=400,
                system=SYSTEM,
                output_config={"effort": "low"},
                messages=[{"role": "user", "content": user}],
            )
            text = "".join(b.text for b in resp.content if b.type == "text")
            total_in += resp.usage.input_tokens
            total_out += resp.usage.output_tokens
            block = f"**Прогон {i}**\n\n{text}\n"
            print(block)
            out.append(block)
    cost = total_in / 1e6 * PRICE_IN + total_out / 1e6 * PRICE_OUT
    footer = (f"\nТокены: вход {total_in}, выход {total_out}. "
              f"Оценка стоимости: ${cost:.5f}\n")
    print(footer)
    out.append(footer)
    Path(__file__).with_name("voice_test2_results.md").write_text(
        "\n".join(out), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
