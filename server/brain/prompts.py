def trait_phrase(pet, limit=3):
    scored = []
    for t, (hi, lo) in TRAIT_WORDS.items():
        v = pet.traits[t]
        if v >= 62:
            scored.append((v - 50, hi))
        elif v <= 38:
            scored.append((50 - v, lo))
    scored.sort(reverse=True)
    return ", ".join(w for _, w in scored[:limit]) or "обыкновенный"


