"""Запасные реплики движка: без Claude, по стадии речи и исходу."""

SOUNDS = ["ууу...", "ммр", "~ ? ~", "!?", "хрр", "~ ~ ~"]
STAGE2 = {
    "accept": ["ладно.", "хм. ну.", "можно."],
    "refuse": ["нет.", "не хочу.", "потом."],
}
STAGE3 = {
    "accept": ["Допустим. Согласен условно.", "Принято к исполнению, лаборант."],
    "refuse": ["Отказываю. Причины секретны.", "Не сейчас. Занят важным."],
}
STAGE4 = {
    "accept": ["Рассмотрел предложение и, к собственному удивлению, одобряю.",
               "Докладываю: согласие получено, но без восторга."],
    "refuse": ["Докладываю: отказ мотивирован, подробности будут в докладной.",
               "Предложение отклонено. Ухо отказывается это слушать."],
}


def fallback_say(stage, is_accept, rng):
    if stage <= 1:
        return rng.choice(SOUNDS)
    table = {2: STAGE2, 3: STAGE3}.get(stage, STAGE4)
    return rng.choice(table["accept" if is_accept else "refuse"])
